#!/usr/bin/env python
"""Markdown tables from the CSVs written by scripts/final_stats.py -> <out>/tables.md. Formatting only (no statistics).
  python scripts/final_tables.py --out results/final_dryrun"""
import argparse, json
from pathlib import Path
import numpy as np
import pandas as pd


def _blank(x):
    return x is None or (isinstance(x, str) and x == "") or (not isinstance(x, str) and pd.isna(x))


def pct(x):
    return "" if _blank(x) else f"{100 * float(x):.1f}"


def pv(x):
    return "" if _blank(x) else (f"{float(x):.2e}" if float(x) < 1e-3 else f"{float(x):.4f}")


def read(p):
    try:
        return pd.read_csv(p)
    except (FileNotFoundError, pd.errors.EmptyDataError):
        return pd.DataFrame()


def md(df, cols, fmt):
    if df.empty:
        return "_none_\n"
    lines = ["| " + " | ".join(h for h, _ in cols) + " |", "|" + "---|" * len(cols)]
    for r in df.to_dict("records"):
        lines.append("| " + " | ".join(fmt.get(c, str)(r.get(c, "")) if c in r else "" for _, c in cols) + " |")
    return "\n".join(lines) + "\n"


CMP = [("analysis", "analysis"), ("subset", "subset"), ("set/rtype", "setrt"), ("method", "method"), ("vs", "comparator"),
       ("seeds", "seeds"), ("n", "n"), ("succ A %", "success_a"), ("succ B %", "success_b"), ("diff pts", "diff"),
       ("A only / B only", "disc"), ("p McNemar (1-sided)", "p_mcnemar"), ("boot lower (1-sided 95%)", "boot_lower_one_sided"),
       ("boot 95% CI", "ci"), ("margin", "margin"), ("p NI", "p_ni"), ("non-inf.", "noninferior"),
       ("missing A/B", "miss"), ("complete-case n / diff", "cc")]
F = dict(success_a=pct, success_b=pct, diff=pct, p_mcnemar=pv, boot_lower_one_sided=pct, margin=pct, p_ni=pv)


def prep(df):
    if df.empty:
        return df
    df = df.copy()
    df["setrt"] = df.set.astype(str) + "/" + df.rtype.astype(str)
    df["seeds"] = df.get("seed_a", "").astype(str) + "/" + df.get("seed_b", "").astype(str)
    df["disc"] = df.get("a_only", "").astype(str) + " / " + df.get("b_only", "").astype(str)
    df["ci"] = ["" if pd.isna(a) else f"[{100*a:.1f}, {100*b:.1f}]" for a, b in zip(df.get("boot_ci_lo", np.nan), df.get("boot_ci_hi", np.nan))]
    df["miss"] = df.get("n_missing_a", "").astype(str) + "/" + df.get("n_missing_b", "").astype(str)
    df["cc"] = ["" if pd.isna(n) else f"{int(n)} / {100*d:+.1f}" for n, d in zip(df.get("cc_n", np.nan), df.get("cc_diff", np.nan))]
    for c in ("subset", "margin", "p_ni", "noninferior"):
        if c not in df:
            df[c] = np.nan
    return df.fillna("")


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", required=True); a = ap.parse_args()
    o = Path(a.out)
    prov = json.loads((o / "provenance.json").read_text()) if (o / "provenance.json").exists() else {}
    t = [f"# Final evaluation tables ({prov.get('mode', '?')})", "",
         "Generated by scripts/final_tables.py from scripts/final_stats.py outputs. Success = top-1 sym-RMSD <= 2 A. "
         "Records without a result row count as failures for every method; timeouts are failures. Not independently verified.", ""]
    if prov.get("notes"):
        t += ["**Notes**", ""] + [f"- {n}" for n in prov["notes"]] + [""]
    t += ["## Holm family (C1-C3)", "", md(read(o / "holm.csv"), [("claim", "claim"), ("p raw", "p_raw"), ("p Holm", "p_holm"),
          ("reject H0", "reject_H0"), ("complete family", "complete_family")], dict(p_raw=pv, p_holm=pv))]
    t += ["## Confirmatory comparisons", "", md(prep(read(o / "claims.csv")), CMP, F)]
    t += ["## C2 wall time (one-sided Wilcoxon)", "", md(read(o / "c2_timing.csv"), [("method", "method"), ("vs", "comparator"),
          ("n", "n"), ("median s A", "median_wall_a"), ("median s B", "median_wall_b"), ("p", "p_wilcoxon"), ("note", "note")],
          dict(median_wall_a=lambda x: f"{float(x):.2f}", median_wall_b=lambda x: f"{float(x):.2f}", p_wilcoxon=pv))]
    t += ["## C1 gap closed", "", md(read(o / "c1_gap_closed.csv"), [("set", "set"), ("GNINA holo-AF gap", "gap"),
          ("reported", "reported"), ("closed", "closed"), ("CI lo", "ci_lo"), ("CI hi", "ci_hi")],
          dict(gap=pct, closed=pct, ci_lo=pct, ci_hi=pct))]
    t += ["## C4 logistic (exploratory)", "", md(read(o / "c4_logit.csv"), [("term", "term"), ("coef", "coef"), ("SE", "se"),
          ("p", "p")], dict(coef=lambda x: f"{float(x):+.3f}", se=lambda x: f"{float(x):.3f}", p=pv))]
    t += ["## C5 AF-hybrid per tier (exploratory, A3)", "", md(prep(read(o / "c5.csv")), [("tier", "tier")] + CMP[1:], F)]
    t += ["## Secondary / robustness", "", md(prep(read(o / "secondary.csv")), CMP, F)]
    ss = read(o / "success_summary.csv")
    if not ss.empty:
        piv = ss[ss.seed.astype(str) != "mean"].pivot_table(index=["set", "rtype", "method"], columns="seed", values="success").reset_index()
        mean = ss[ss.seed.astype(str) == "mean"].set_index(["set", "rtype", "method"])
        piv["mean"] = [mean.success.get(tuple(k), np.nan) for k in piv[["set", "rtype", "method"]].values]
        piv["sd"] = [mean.success_sd.get(tuple(k), np.nan) for k in piv[["set", "rtype", "method"]].values]
        piv["n"] = [mean.n_universe.get(tuple(k), np.nan) for k in piv[["set", "rtype", "method"]].values]
        seeds = [c for c in piv.columns if c not in ("set", "rtype", "method", "mean", "sd", "n")]
        t += ["## Success by method and seed (%)", "", md(piv, [("set", "set"), ("rtype", "rtype"), ("method", "method"), ("n", "n")] +
              [(f"s{s}", s) for s in seeds] + [("mean", "mean"), ("SD", "sd")], {**{s: pct for s in seeds}, "mean": pct, "sd": pct})]
    (o / "tables.md").write_text("\n".join(t))
    print(f"wrote {o / 'tables.md'}")


if __name__ == "__main__":
    main()
